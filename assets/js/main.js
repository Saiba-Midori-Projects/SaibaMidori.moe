console.log('This site was generated by Hugo.');

document.addEventListener('DOMContentLoaded', () => {
  const { body } = document;
  const themeName = body?.dataset.themeName || 'Midori';
  const version = body?.dataset.themeVersion || '0.1.0';
  const hugoVersion = body?.dataset.hugoVersion;
  const openingReveal = document.querySelector('opening-reveal');
  const mobileAppBar = document.querySelector('.mobile-appbar__inner');
  const articleMain = document.querySelector('.card main');
  const toc = document.querySelector('.post-toc');
  const tocToggle = toc?.querySelector('.post-toc__toggle');
  const tocToggleLabel = tocToggle?.querySelector('span');
  const mobileTocToggle = document.querySelector('.mobile-toc-toggle');
  const tocBackdrop = document.querySelector('.post-toc__backdrop');
  const tocLinks = toc ? Array.from(toc.querySelectorAll('.post-toc__nav a')) : [];
  const backToTop = document.querySelector('.back-to-top');
  const navToggle = document.querySelector('.site-nav-toggle');
  const siteSidebar = document.querySelector('.site-sidebar');
  const sidebarBackdrop = document.querySelector('.site-sidebar__backdrop');
  const sidebarLinks = siteSidebar ? Array.from(siteSidebar.querySelectorAll('a')) : [];

  if (hugoVersion) {
    console.log(
      `%c Theme ${themeName} %c v${version} %c Hugo ${hugoVersion} `,
      'background: #44c96a; color: #fff; padding: 5px 0; border-radius: 3px 0 0 3px; font-weight: bold;',
      'background: #333; color: #fff; padding: 5px 0; font-weight: bold;',
      'background: #eee; color: #333; padding: 5px 0; border-radius: 0 3px 3px 0;'
    );
  }

  if (openingReveal && typeof openingReveal.play === 'function') {
    openingReveal.play();
  } else {
    body?.classList.add('loaded');
  }

  if (mobileAppBar && articleMain) {
    let progressFrame = 0;

    const updateReadingProgress = () => {
      const top = articleMain.getBoundingClientRect().top + window.scrollY;
      const total = Math.max(articleMain.scrollHeight - window.innerHeight, 1);
      const progress = Math.min(Math.max((window.scrollY - top) / total, 0), 1);

      mobileAppBar.style.setProperty('--reading-progress', progress.toFixed(4));
      progressFrame = 0;
    };

    const requestReadingProgressUpdate = () => {
      if (progressFrame !== 0) {
        return;
      }

      progressFrame = window.requestAnimationFrame(updateReadingProgress);
    };

    window.addEventListener('scroll', requestReadingProgressUpdate, { passive: true });
    window.addEventListener('resize', requestReadingProgressUpdate);
    requestReadingProgressUpdate();
  }

  const setNavOpen = (isOpen) => {
    document.body.classList.toggle('is-nav-open', isOpen);

    if (navToggle) {
      navToggle.setAttribute('aria-expanded', String(isOpen));
      navToggle.setAttribute(
        'aria-label',
        isOpen ? navToggle.dataset.labelClose || '' : navToggle.dataset.labelOpen || ''
      );
    }
  };

  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') {
      setNavOpen(false);
      setToggleState(false);
    }
  });

  if (navToggle && siteSidebar && sidebarBackdrop) {
    navToggle.addEventListener('click', () => {
      setNavOpen(!document.body.classList.contains('is-nav-open'));
    });

    sidebarBackdrop.addEventListener('click', () => {
      setNavOpen(false);
    });

    sidebarLinks.forEach((link) => {
      link.addEventListener('click', () => {
        if (window.innerWidth <= 1024) {
          setNavOpen(false);
        }
      });
    });
  }

  const setToggleState = (isOpen) => {
    if (!toc) {
      return;
    }

    toc.classList.toggle('is-open', isOpen);
    if (tocToggle) {
      tocToggle.setAttribute('aria-expanded', String(isOpen));
    }

    if (mobileTocToggle) {
      mobileTocToggle.setAttribute('aria-expanded', String(isOpen));
      mobileTocToggle.setAttribute(
        'aria-label',
        isOpen ? mobileTocToggle.dataset.labelClose || '' : mobileTocToggle.dataset.labelOpen || ''
      );
    }

    if (tocToggleLabel) {
      tocToggleLabel.textContent = isOpen
        ? tocToggle?.dataset.labelClose || ''
        : tocToggle?.dataset.labelOpen || '';
    }
  };

  if (tocToggle) {
    tocToggle.addEventListener('click', () => {
      setToggleState(!toc.classList.contains('is-open'));
    });
  }

  if (toc && mobileTocToggle) {
    mobileTocToggle.addEventListener('click', () => {
      setToggleState(!toc.classList.contains('is-open'));
    });
  }

  if (tocBackdrop) {
    tocBackdrop.addEventListener('click', () => {
      setToggleState(false);
    });
  }

  if (backToTop) {
    const updateBackToTop = () => {
      backToTop.classList.toggle('is-visible', window.scrollY > 280);
    };

    backToTop.addEventListener('click', () => {
      window.scrollTo({ top: 0, behavior: 'smooth' });
    });

    window.addEventListener('scroll', updateBackToTop, { passive: true });
    updateBackToTop();
  }

  if (tocLinks.length === 0) {
    return;
  }

  const headingMap = tocLinks
    .map((link) => {
      const hash = link.getAttribute('href');

      if (!hash || !hash.startsWith('#')) {
        return null;
      }

      const target = document.getElementById(hash.slice(1));
      return target ? { link, target } : null;
    })
    .filter(Boolean);

  const setActiveLink = (activeId) => {
    headingMap.forEach(({ link, target }) => {
      link.classList.toggle('is-active', target.id === activeId);
    });
  };

  const observer = new IntersectionObserver(
    (entries) => {
      const visible = entries
        .filter((entry) => entry.isIntersecting)
        .sort((a, b) => a.boundingClientRect.top - b.boundingClientRect.top);

      if (visible.length > 0) {
        setActiveLink(visible[0].target.id);
      }
    },
    {
      rootMargin: '0px 0px -70% 0px',
      threshold: 0.1
    }
  );

  headingMap.forEach(({ target }) => observer.observe(target));

  tocLinks.forEach((link) => {
    link.addEventListener('click', () => {
      const hash = link.getAttribute('href');
      if (!hash) {
        return;
      }

      setActiveLink(hash.slice(1));
      if (toc?.classList.contains('is-open')) {
        setToggleState(false);
      }
    });
  });
});
